#!/usr/bin/env node
/**
 * gen-news-meta.mjs — regenerate src/lib/news-meta.generated.ts from
 * content/news/*.mdx. Each MDX file carries an `export const meta = {…}`
 * block; this script reads those blocks and writes a pure-data module so
 * sitemaps and feeds never import React components.
 *
 * Runs automatically before every build (npm run prebuild).
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const newsDir = path.join(root, "content", "news");
const outFile = path.join(root, "src", "lib", "news-meta.generated.ts");

/** Extract and evaluate the `export const meta = {…}` object from MDX source. */
function extractMeta(source, file) {
  const m = source.match(/export\s+const\s+meta\s*=\s*(\{[\s\S]*?\})\s*;?\s*\n/);
  if (!m) {
    throw new Error(`${file}: no \`export const meta\` block found`);
  }
  // The meta block is a plain object literal of strings — evaluate it as an
  // expression. Newlines inside template literals / strings are preserved.
  return eval(`(${m[1]})`);
}

const files = (await readdir(newsDir))
  .filter((f) => f.endsWith(".mdx"))
  .sort();

const posts = [];
for (const f of files) {
  const source = await readFile(path.join(newsDir, f), "utf8");
  const meta = extractMeta(source, f);
  if (!meta.slug) meta.slug = f.replace(/^\d{4}-\d{2}-\d{2}-/, "").replace(/\.mdx$/, "");
  for (const key of ["title", "date", "category", "description"]) {
    if (!meta[key]) throw new Error(`${f}: meta is missing "${key}"`);
  }
  if (!["announcement", "fieldnote", "press"].includes(meta.category)) {
    throw new Error(`${f}: category "${meta.category}" is not announcement|fieldnote|press`);
  }
  posts.push(meta);
}

// Stable order (filename/date ascending) — getNews() re-sorts newest-first
// at runtime, so the generated file just needs to be deterministic.
posts.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : a.slug.localeCompare(b.slug)));

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
const body = posts
  .map((p) => {
    const lines = [
      "  {",
      `    slug: "${esc(p.slug)}",`,
      `    title: "${esc(p.title)}",`,
      `    date: "${esc(p.date)}",`,
      `    category: "${esc(p.category)}" as NewsCategory,`,
      `    description: "${esc(p.description)}",`,
    ];
    if (p.standfirst) lines.push(`    standfirst: "${esc(p.standfirst)}",`);
    lines.push("  },");
    return lines.join("\n");
  })
  .join("\n");

const out = `/* AUTO-GENERATED by scripts/gen-news-meta.mjs — do not edit by hand.
 * Pure data extracted from content/news/*.mdx so sitemaps and feeds
 * never import React components. Regenerate with: npm run prebuild */
import type { NewsCategory, NewsMeta } from "./news-types";

export const newsMeta: NewsMeta[] = [
${body}
];

export type { NewsCategory, NewsMeta };
`;

await writeFile(outFile, out, "utf8");
console.log(`gen-news-meta: ${posts.length} post(s) → src/lib/news-meta.generated.ts`);
